"""Strict readers for archived IDyOM *predictions*, not an IDyOM engine.

The third-party thesis supplies eight rows of candidate probabilities for each
of the Cuddy–Lunney and Schellenberg human-listener studies. File ordering and
candidate identity are part of the scientific contract: there is no inferred
join and no assumption that the original IDyOM model has been run locally.
"""

from __future__ import annotations

import csv
import re
from pathlib import Path
from xml.etree import ElementTree
from zipfile import ZipFile

import numpy as np


def _probability(value: str) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError("invalid_archived_probability") from exc
    if not np.isfinite(number) or not 0 <= number <= 1:
        raise ValueError("invalid_archived_probability")
    return number


def _validate_distribution(pitches: list[float], expected: int) -> np.ndarray:
    if len(pitches) != expected:
        raise ValueError("archived_candidate_count_mismatch")
    values = np.asarray(pitches, dtype=float)
    # Only a pitch *subset* is present; its mass cannot exceed a full
    # distribution. Normalization would not change within-context ranks.
    if not (0 < values.sum() <= 1.00001):
        raise ValueError("invalid_archived_probability_mass")
    return values


def archived_cuddy_cpitch(path: Path) -> list[np.ndarray]:
    """Eight rows, MIDI pitches 54..78 in ascending order, not arbitrary bins."""
    with path.open(newline="", encoding="utf-8-sig") as stream:
        reader = csv.reader(stream)
        header = next(reader)
        expected = ["melody.id", "melody.name", *
                    [f"idyom prob {note}" for note in range(54, 79)]]
        if header != expected:
            raise ValueError("cuddy_archived_pitch_header_mismatch")
        rows = list(reader)
    if len(rows) != 8:
        raise ValueError("cuddy_archived_context_count_mismatch")
    predictions = []
    for index, row in enumerate(rows, start=1):
        if len(row) != 27 or row[:2] != [str(index), f"cudlun95-{index}_with_probe"]:
            raise ValueError("cuddy_archived_context_identity_mismatch")
        predictions.append(_validate_distribution([_probability(v) for v in row[2:]], 25))
    return predictions


def archived_schellenberg_probs(path: Path) -> list[np.ndarray]:
    """Eight rows of 15 diatonic probabilities, in source workbook order."""
    with path.open(newline="", encoding="utf-8-sig") as stream:
        reader = csv.reader(stream)
        if next(reader) != ["fragment", *["idyom probability"] * 15]:
            raise ValueError("schell_archived_column_header_mismatch")
        rows = list(reader)
    if len(rows) != 8:
        raise ValueError("schell_archived_fragment_count_mismatch")
    predictions = []
    for index, row in enumerate(rows, start=1):
        if len(row) != 16 or row[0] != str(index):
            raise ValueError("schell_archived_fragment_identity_mismatch")
        predictions.append(_validate_distribution([_probability(v) for v in row[1:]], 15))
    return predictions


def schellenberg_workbook_pitches(path: Path) -> list[np.ndarray]:
    """Read the thesis' xlsx pitch columns with only Python's standard library.

    Unlike a comparison of two CSVs generated by the same script, this checks
    each of the 120 probability columns against the *independently recovered*
    candidates from the reconstructed MIDI and its key signature. Values are
    numeric OOXML cells; human ratings are never opened here.
    """
    namespace = {"x": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
    with ZipFile(path) as workbook:
        root = ElementTree.fromstring(workbook.read("xl/worksheets/sheet1.xml"))
    result: dict[str, list[int]] = {chr(x): [] for x in range(ord("A"), ord("I"))}
    for cell in root.findall(".//x:sheetData/x:row/x:c", namespace):
        address = cell.get("r", "")
        match = re.fullmatch(r"([A-H])(\d+)", address)
        if not match or int(match.group(2)) <= 1:
            continue
        value = cell.find("x:v", namespace)
        if value is None or value.text is None:
            continue
        number = float(value.text)
        if not number.is_integer() or not 0 <= number <= 127:
            raise ValueError("invalid_schell_workbook_pitch")
        result[match.group(1)].append(int(number))
    if any(len(pitches) != 15 for pitches in result.values()):
        raise ValueError("schell_workbook_candidate_count_mismatch")
    return [np.asarray(result[chr(letter)], dtype=int)
            for letter in range(ord("A"), ord("I"))]
